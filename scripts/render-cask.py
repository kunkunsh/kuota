#!/usr/bin/env python3
"""Render the Homebrew cask from real app-v* release artifacts.

Runs in CI (release.yml brew-tap job). Reads the downloaded dmg files,
computes sha256, and writes the final cask to /tmp/kuota.rb, which the
job attaches to the release; can be copied into HuakunShen/homebrew-tap.
"""
import glob
import hashlib
import os
import sys

version = os.environ.get("VERSION_REF", "0.1.0").removeprefix("app-v")
repo = os.environ.get("REPO", "kunkunsh/kuota")

arm = x64 = None
for dmg in sorted(glob.glob("/tmp/dmg/*.dmg")):
    name = os.path.basename(dmg)
    sha = hashlib.sha256(open(dmg, "rb").read()).hexdigest()
    if "aarch64" in name:
        arm = (sha, name)
    elif "x64" in name or "x86_64" in name:
        x64 = (sha, name)

if arm is None or x64 is None:
    print(f"Warning: found arm={arm}, x64={x64}", file=sys.stderr)
    if arm is None and x64 is None:
        sys.exit(f"missing dmg artifacts in /tmp/dmg: arm={arm} x64={x64}")
    if arm is None:
        arm = (x64[0], x64[1])
    if x64 is None:
        x64 = (arm[0], arm[1])

cask = """# Generated by release.yml (brew-tap job) from the app-v__VERSION__ release.
# Source of truth: packaging/homebrew/Casks/kuota.rb in the kuota repo.
cask "kuota" do
  arch arm: "aarch64", intel: "x64"

  version "__VERSION__"
  sha256 arm:   "__ARM_SHA__",
         intel: "__X64_SHA__"

  url "https://github.com/__REPO__/releases/download/app-v#{version}/Kuota_#{version}_#{arch}.dmg"
  name "Kuota"
  desc "Truthful multi-provider AI subscription & quota monitor (Codex, Claude, Antigravity)"
  homepage "https://github.com/__REPO__"

  livecheck do
    url "https://github.com/__REPO__/releases/latest"
    strategy :github_latest do |json|
      json["tag_name"]&.sub(/^app-v/, "")
    end
  end

  auto_updates true

  app "Kuota.app"

  zap trash: [
    "~/Library/Application Support/sh.kunkun.kuota.desktop",
    "~/Library/WebKit/sh.kunkun.kuota.desktop",
    "~/Library/Caches/sh.kunkun.kuota.desktop",
  ]
end
"""
cask = (
    cask.replace("__VERSION__", version)
    .replace("__ARM_SHA__", arm[0])
    .replace("__X64_SHA__", x64[0])
    .replace("__REPO__", repo)
)

out = "/tmp/kuota.rb"
with open(out, "w") as handle:
    handle.write(cask)
print(f"wrote {out} ({len(cask)} bytes)")

pkg_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "packaging", "homebrew", "Casks")
if os.path.isdir(pkg_dir):
    with open(os.path.join(pkg_dir, "kuota.rb"), "w") as handle:
        handle.write(cask)
    print(f"wrote {pkg_dir}/kuota.rb")
